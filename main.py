MORNING_FORECAST_HOUR = 7
MORNING_FORECAST_MINUTE = 10


def run_morning_forecast_scheduler():
    while True:
        now = datetime.now(KYIV_TZ)
        target = now.replace(hour=MORNING_FORECAST_HOUR, minute=MORNING_FORECAST_MINUTE, second=0, microsecond=0)
        if now >= target:
            target += timedelta(days=1)
        sleep_seconds = (target - now).total_seconds()
        time.sleep(sleep_seconds)

        try:
            message_text = generate_morning_forecast_message()
            for chat_id in ALLOWED_CHAT_IDS:
                if is_asleep(chat_id):
                    continue
                bot.send_message(chat_id, message_text)
        except Exception as e:
            print(f"Не зміг надіслати ранковий прогноз: {e}")

        time.sleep(60)


@bot.message_handler(content_types=['text'])
def handle_text(message):
    try:
        chat_id = message.chat.id

        # якщо новинний "канал" насправді Group, а не Channel - пости приходять
        # як звичайний message, а не channel_post
        if chat_id == NEWS_CHANNEL_ID and message.text:
            print(f"[NEWS CHANNEL via message] Публікую: {message.text[:120]}...")
            publish_news_post(message.text.strip())
            return

        if chat_id not in ALLOWED_CHAT_IDS:
            return

        if is_sleep_command(message.text or ""):
            if not is_admin_message(message):
                try:
                    bot.reply_to(message, random.choice(SLEEP_DENIED_REPLIES))
                except Exception as e:
                    print(f"Не зміг відповісти на невдалу спробу сну: {e}")
                return
            sleep_until[chat_id] = time.time() + SLEEP_DURATION
            try:
                bot.reply_to(message, random.choice([
                    "та все, йду спати, не будіть",
                    "спати пішов, до зустрічі",
                    "всє, баю-бай на годинку",
                    "йду в анабіоз, чатік без мене поки",
                ]))
            except Exception as e:
                print(f"Не зміг відповісти на команду сну: {e}")
            return

        chat_name = message.chat.title or "Чат"
        is_admin = is_admin_message(message)
        user_name = "Адмін (анонімно)" if (message.sender_chat and message.sender_chat.id == chat_id) else (message.from_user.first_name or "Юзер")
        user_input = message.text or ""

        chat_history[chat_id].append(f"{user_name}: {user_input}")

        if not should_call_ai(message):
            return

        history_text = "\n".join(chat_history[chat_id])
        current_datetime = get_ua_datetime_str()
        current_weather = get_weather_str()

        alerts_context = ""
        if has_alert_keyword(user_input):
            alerts_context = f"\n\nДані з каналу «Тривожні Валки» (для довідки, не копіюй диспетчерські фрази):\n{get_alerts_context()}\n"

        # без цього модель бачить лише ПОТОЧНУ погоду і вигадує решту дня з голови
        weather_context = ""
        if has_weather_keyword(user_input):
            try:
                periods_text = get_forecast_periods_text()
                weather_context = (
                    f"\n\nТочний погодинний прогноз на сьогодні у Валках (ЄДИНЕ джерело правди про погоду - "
                    f"НЕ вигадуй свої цифри, використовуй тільки ці дані):\n{periods_text}\n"
                )
            except Exception as e:
                print(f"Не зміг отримати погодинний прогноз для відповіді: {e}")

        admin_context = ""
        if is_admin:
            admin_context = (
                "\n\nВАЖЛИВО: останнє повідомлення написав адмін чату (можливо анонімно, від імені групи). "
                "Постався з повагою, без токсичного тону в його адресу, можеш звертатись «адміни,» замість імені.\n"
            )

        formatted_prompt = (
            f"Поточна дата і час (Київ): {current_datetime}\n"
            f"Погода зараз у Валках: {current_weather}\n"
            f"Чат: {chat_name}\n"
            f"Останні повідомлення в чаті:\n{history_text}\n\n"
            f"Останнє повідомлення від {user_name}, на яке треба зреагувати (або видати IGNORE): {user_input}"
            f"{alerts_context}"
            f"{weather_context}"
            f"{admin_context}"
        )

        response = client.models.generate_content(
            model="gemini-3.1-flash-lite",
            contents=formatted_prompt,
            config={"system_instruction": SYSTEM_PROMPT}
        )
        raw_answer = response.text.strip()

        # модель іноді дописує "IGNORE" в кінці нормальної відповіді про всяк випадок - зрізаємо хвіст
        raw_answer = re.sub(r'\s*\bIGNORE\b\.?\s*$', '', raw_answer, flags=re.IGNORECASE).strip()

        answer = normalize_olegs_style(raw_answer)

        letters_only = re.sub(r'[^a-zA-Zа-яА-ЯіІїЇєЄґҐ]', '', answer).strip().upper()
        if letters_only == "IGNORE":
            return

        if not answer:
            return

        first_word = answer.split()[0].upper().strip(".,!?\"'") if answer else ""
        if answer and first_word != "IGNORE":
            bot.reply_to(message, answer)
            chat_history[chat_id].append(f"Бот: {answer}")
            last_ai_reply_time[chat_id] = time.time()
            last_replied_user[chat_id] = message.from_user.id
    except Exception as e:
        print(f"ПОМИЛКА в handle_text: {e}")


