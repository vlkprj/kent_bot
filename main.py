def is_admin_message(message) -> bool:
    """
    Перевіряє чи повідомлення від реального адміна.
    Якщо адмін пише анонімно від імені групи, Telegram підміняє
    message.from_user на службового GroupAnonymousBot, тому звичайна
    перевірка по from_user.id не спрацює. Ознака анонімного адміна -
    message.sender_chat.id == message.chat.id (пост "від імені групи",
    а таке право є тільки в адмінів).
    """
    if message.sender_chat is not None and message.sender_chat.id == message.chat.id:
        return True
    return message.from_user.id in get_chat_admin_ids(message.chat.id)


