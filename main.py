weather_cache = {"text": "погода невідома (ще не оновилась)", "updated_at": 0}
WEATHER_REFRESH_SECONDS = 2400


def fetch_weather() -> str:
    url = (
        f"https://api.open-meteo.com/v1/forecast"
        f"?latitude={VALKY_LAT}&longitude={VALKY_LON}"
        f"&current=temperature_2m,apparent_temperature,weather_code,wind_speed_10m"
        f"&timezone=Europe/Kyiv"
    )
    with urllib.request.urlopen(url, timeout=10) as response:
        data = json.loads(response.read().decode())

    current = data["current"]
    temp = round(current["temperature_2m"])
    feels_like = round(current["apparent_temperature"])
    wind = round(current["wind_speed_10m"])
    code = current["weather_code"]
    description = WEATHER_CODE_MAP.get(code, "хз шо там за погода")

    return f"{description}, {temp}°C (відчувається як {feels_like}°C), вітер {wind} км/год"


def get_weather_str() -> str:
    now = time.time()
    if now - weather_cache["updated_at"] > WEATHER_REFRESH_SECONDS:
        try:
            weather_cache["text"] = fetch_weather()
            weather_cache["updated_at"] = now
        except Exception as e:
            print(f"Не зміг оновити погоду: {e}")
    return weather_cache["text"]


def get_daily_forecast_data() -> dict:
    url = (
        f"https://api.open-meteo.com/v1/forecast"
        f"?latitude={VALKY_LAT}&longitude={VALKY_LON}"
        f"&hourly=temperature_2m,apparent_temperature,weather_code,precipitation_probability"
        f"&timezone=Europe/Kyiv&forecast_days=2"
    )
    with urllib.request.urlopen(url, timeout=10) as response:
        data = json.loads(response.read().decode())

    hourly = data["hourly"]
    times = hourly["time"]
    now = datetime.now(KYIV_TZ)
    today_str = now.strftime("%Y-%m-%d")
    tomorrow_str = (now + timedelta(days=1)).strftime("%Y-%m-%d")

    target_points = {
        "зараз": f"{today_str}T{now.strftime('%H')}:00",
        "до обіду": f"{today_str}T12:00",
        "під вечір": f"{today_str}T18:00",
        "вночі": f"{tomorrow_str}T02:00",
    }

    result = {}
    for label, target_time in target_points.items():
        if target_time in times:
            idx = times.index(target_time)
        else:
            idx = min(range(len(times)), key=lambda i: abs(
                datetime.fromisoformat(times[i]) - datetime.fromisoformat(target_time)
            ))
        result[label] = {
            "temp": round(hourly["temperature_2m"][idx]),
            "feels_like": round(hourly["apparent_temperature"][idx]),
            "precip_chance": hourly["precipitation_probability"][idx],
            "description": WEATHER_CODE_MAP.get(hourly["weather_code"][idx], "хз шо там за погода"),
        }

    return result


